#!/usr/bin/env python3
"""Index the earlier Pilot 2 attempts from their stored records (docs/PILOT_2.md section 9, #237).

    python scripts/pilot2_attempts.py

A paper whose run was stopped by a defect in Repro Radar is re-run after the fix, and the earlier attempt is kept as
evidence in `data/pilot2_runs/first_attempts/<paper_id>_attempt<N>/`. This script reads the `pilot_record.json` and
`run_report.json` of each of them and writes `index.json` and `README.md` next to them: the Repro Radar commit, how
far the attempt got, how it ended, and why it was superseded. The reason is an explanation written by hand in
`reasons.json` (with the issue that fixed it); every other column comes from the stored files.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

project_root = Path(__file__).resolve().parent.parent
ATTEMPTS_DIR = project_root / "data" / "pilot2_runs" / "first_attempts"
NAME_RE = re.compile(r"^(paper_\d+)_attempt(\d+)$")


def _load(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}


def describe(attempt_dir: Path, reasons: dict[str, str]) -> dict[str, Any]:
    match = NAME_RE.match(attempt_dir.name)
    if not match:
        raise ValueError(f"not an attempt directory: {attempt_dir.name}")
    record = _load(attempt_dir / "pilot_record.json")
    report = _load(attempt_dir / "run_report.json")
    run = record.get("run") or {}
    return {
        "attempt": attempt_dir.name,
        "paper_id": match.group(1),
        "number": int(match.group(2)),
        "repro_radar_commit": (record.get("repro_radar_commit") or "unknown")[:7],
        "stage": (record.get("stage") or {}).get("status"),
        "build": (record.get("build") or {}).get("status"),
        "install": report.get("dependency_install_status") or run.get("dependency_install_status"),
        "run": run.get("status"),
        "exit_code": run.get("exit_code"),
        "superseded_because": reasons.get(attempt_dir.name),
    }


def index(attempts_dir: Path = ATTEMPTS_DIR) -> list[dict[str, Any]]:
    reasons = _load(attempts_dir / "reasons.json")
    rows = [describe(d, reasons) for d in sorted(attempts_dir.iterdir()) if d.is_dir() and NAME_RE.match(d.name)]
    return sorted(rows, key=lambda r: (r["paper_id"], r["number"]))


def to_markdown(rows: list[dict[str, Any]]) -> str:
    cell = lambda v: "none" if v in (None, "") else str(v)
    lines = ["<!-- Generated by scripts/pilot2_attempts.py from the stored records; do not edit by hand. -->", "",
             "# Earlier Pilot 2 attempts", "",
             ("Each attempt is kept as evidence (`docs/PILOT_2.md` section 9). The columns come from the stored "
              "`pilot_record.json` and `run_report.json`; the last column is written by hand in `reasons.json`."), "",
             "| Attempt | Repro Radar commit | Stage | Build | Install | Run | Exit code | Superseded because |",
             "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| `{r['attempt']}` | `{r['repro_radar_commit']}` | {cell(r['stage'])} | {cell(r['build'])} | "
                     f"{cell(r['install'])} | {cell(r['run'])} | {cell(r['exit_code'])} | {cell(r['superseded_because'])} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Index the earlier Pilot 2 attempts from their stored records.")
    parser.add_argument("--dir", default=str(ATTEMPTS_DIR))
    args = parser.parse_args(argv)
    attempts_dir = Path(args.dir)
    rows = index(attempts_dir)
    missing = [r["attempt"] for r in rows if not r["superseded_because"]]
    (attempts_dir / "index.json").write_text(json.dumps(rows, indent=2) + "\n", encoding="utf-8")
    markdown = to_markdown(rows)
    (attempts_dir / "README.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    if missing:
        print(f"no reason in reasons.json for: {', '.join(missing)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
