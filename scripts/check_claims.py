#!/usr/bin/env python3
"""Run the verbatim quote guard (W4) on every claim of the agent extractions (plan step 1.4, #182).

For each paper in data/claims/, every found answer of passes A and B is checked with src/quote_guard.py against the
pinned PDF's page text (data/pdfs/<paper_id>.pdf, downloaded by scripts/extract_claims.py; not committed). Writes
data/claims/guard_report.json and data/claims/guard_report.md. Exit code 0 = every claim passed, 1 = not.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.claim_schema import ExtractedClaim
from src.config import DATA_DIR
from src.pdf_text import PdfText, extract_pdf_text
from src.quote_guard import AUTO_QUOTE_MATCH, verify_claim

CLAIMS_DIR = DATA_DIR / "claims"
PDF_DIR = DATA_DIR / "pdfs"


def check_record(record: dict[str, Any], pdf: PdfText) -> list[dict[str, Any]]:
    rows = []
    for label in sorted(record["extractions"]):
        for qid, answer in record["extractions"][label]["answers"].items():
            row: dict[str, Any] = {"paper_id": record["paper_id"], "pass": label, "query_id": qid,
                                   "answer": answer["status"]}
            if answer["status"] == "found":
                claim = ExtractedClaim(**answer["claim"])
                result = verify_claim(claim, pdf, record["pdf_sha256"])
                row.update(value_as_printed=claim.value_as_printed, page=claim.page, status=result.status,
                           quote_match=result.checks.get("quote_match"), value_match=result.checks.get("value_match"),
                           from_table=result.checks.get("from_table"), reasons=result.reasons)
            rows.append(row)
    return rows


def check(claims_dir: Path = CLAIMS_DIR, pdf_dir: Path = PDF_DIR) -> dict[str, Any]:
    rows = []
    for path in sorted(claims_dir.glob("paper_*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        rows += check_record(record, extract_pdf_text(pdf_dir / f"{record['paper_id']}.pdf"))
    found = [r for r in rows if r["answer"] == "found"]
    passed = [r for r in found if r["status"] == AUTO_QUOTE_MATCH]
    return {"guard": "src/quote_guard.py", "answers": len(rows), "found_claims": len(found),
            "auto_quote_match": len(passed), "unverified": len(found) - len(passed),
            "from_table": sum(1 for r in found if r["from_table"]), "rows": rows}


def to_markdown(result: dict[str, Any]) -> str:
    lines = ["<!-- Generated by scripts/check_claims.py; do not edit by hand. -->", "",
             (f"Answers: {result['answers']}. Found claims: {result['found_claims']}. "
              f"AUTO_QUOTE_MATCH: {result['auto_quote_match']}. UNVERIFIED: {result['unverified']}. "
              f"From tables (owner review in W7): {result['from_table']}."), "",
             "| Paper | Pass | Question | Value | Page | Guard | Quote match | Value match | Table | Reasons |",
             "|---|---|---|---|---|---|---|---|---|---|"]
    for r in result["rows"]:
        if r["answer"] != "found":
            lines.append(f"| `{r['paper_id']}` | {r['pass']} | `{r['query_id']}` | not found | | | | | | |")
            continue
        lines.append(f"| `{r['paper_id']}` | {r['pass']} | `{r['query_id']}` | `{r['value_as_printed']}` | {r['page']} "
                     f"| {r['status']} | {r['quote_match']} | {r['value_match']} | {'yes' if r['from_table'] else 'no'} "
                     f"| {'; '.join(r['reasons'])} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Run the quote guard on the agent extractions.")
    parser.add_argument("--claims-dir", default=str(CLAIMS_DIR))
    parser.add_argument("--pdf-dir", default=str(PDF_DIR))
    args = parser.parse_args(argv)
    claims_dir = Path(args.claims_dir)
    result = check(claims_dir, Path(args.pdf_dir))
    (claims_dir / "guard_report.json").write_text(json.dumps(result, indent=2, ensure_ascii=False) + "\n",
                                                  encoding="utf-8")
    markdown = to_markdown(result)
    (claims_dir / "guard_report.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    return 0 if result["unverified"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
