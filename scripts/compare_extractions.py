#!/usr/bin/env python3
"""Compare the two extraction passes by normalized value (plan step 1.2, #179; D-005).

For each paper in data/claims/ and each question, passes A and B AGREE if both answered not_found, or both found a
claim with the same `value_normalized`. Quote text, reasons, and field names may differ. Everything else is a
DISAGREEMENT (different values, or found in one pass and not_found in the other); every disagreement goes to the owner
in W7 (#134). Writes data/claims/consistency.json and data/claims/consistency.md. Exit code 0 = all agree, 1 = not.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.claim_schema import ExtractedClaim
from src.config import DATA_DIR

CLAIMS_DIR = DATA_DIR / "claims"


def _value(answer: dict[str, Any]) -> float | None:
    if answer["status"] != "found":
        return None
    return ExtractedClaim(**answer["claim"]).value_normalized  # recomputed by the schema rule, not trusted from file


def compare_answers(a: dict[str, Any], b: dict[str, Any]) -> dict[str, Any]:
    va, vb = _value(a), _value(b)
    if a["status"] == b["status"] == "not_found":
        verdict = "agree_not_found"
    elif a["status"] == b["status"] == "found" and va == vb:
        verdict = "agree_value"
    elif a["status"] == b["status"] == "found":
        verdict = "value_mismatch"
    else:
        verdict = "found_vs_not_found"
    return {"verdict": verdict, "agree": verdict.startswith("agree"), "a": va, "b": vb,
            "a_status": a["status"], "b_status": b["status"]}


def compare(claims_dir: Path = CLAIMS_DIR) -> dict[str, Any]:
    rows = []
    for path in sorted(claims_dir.glob("paper_*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        a, b = record["extractions"]["A"]["answers"], record["extractions"]["B"]["answers"]
        if set(a) != set(b):
            raise ValueError(f"{path.name}: passes A and B answer different questions")
        for qid in a:
            rows.append({"paper_id": record["paper_id"], "query_id": qid, **compare_answers(a[qid], b[qid])})
    disagreements = [r for r in rows if not r["agree"]]
    return {"rule": "docs/DECISIONS.md D-005", "questions": len(rows), "agreements": len(rows) - len(disagreements),
            "disagreements": len(disagreements), "rows": rows}


def to_markdown(result: dict[str, Any]) -> str:
    lines = ["<!-- Generated by scripts/compare_extractions.py; do not edit by hand. -->", "",
             (f"Questions: {result['questions']}. Agreements: {result['agreements']}. "
              f"Disagreements: {result['disagreements']}."), "",
             "| Paper | Question | Pass A | Pass B | Verdict |", "|---|---|---|---|---|"]
    for r in result["rows"]:
        a = r["a"] if r["a_status"] == "found" else "not found"
        b = r["b"] if r["b_status"] == "found" else "not found"
        lines.append(f"| `{r['paper_id']}` | `{r['query_id']}` | {a} | {b} | {r['verdict']} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare extraction passes A and B by normalized value.")
    parser.add_argument("--claims-dir", default=str(CLAIMS_DIR))
    args = parser.parse_args(argv)
    claims_dir = Path(args.claims_dir)
    result = compare(claims_dir)
    (claims_dir / "consistency.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    markdown = to_markdown(result)
    (claims_dir / "consistency.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    return 0 if result["disagreements"] == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
