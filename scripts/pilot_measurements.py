#!/usr/bin/env python3
"""Compute the Week 2 pilot measurements from the stored run files (P3, #124).

Reads `data/pilot_runs/<paper_id>/` for every paper in data/seed_papers.json and applies the definitions frozen in
docs/PILOT_WEEK2.md section 5. Writes `data/pilot_runs/measurements.json` and `data/pilot_runs/measurements.md`;
every number in the pilot report comes from these files, not from hand typing.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.config import SEED_PAPERS_PATH  # noqa: E402

PILOT_RUNS_DIR = project_root / "data" / "pilot_runs"
MIB = 1024 * 1024


def _load(path: Path) -> Optional[Dict[str, Any]]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def paper_measurement(paper_id: str, runs_dir: Path) -> Dict[str, Any]:
    """One paper's result under the protocol definitions (section 5)."""
    paper_dir = runs_dir / paper_id
    record = _load(paper_dir / "pilot_record.json") or {}
    report = _load(paper_dir / "run_report.json")
    install_meta = _load(paper_dir / "install_meta.json") or {}

    if report is None:
        # No sandbox run: staging failed or the harness stopped before the run. Counts as a failure.
        return {
            "paper_id": paper_id,
            "valid_run": False,
            "install_success": False,
            "run_success": False,
            "pilot_success": False,
            "stage_status": (record.get("stage") or {}).get("status", "MISSING"),
            "dependency_install_status": None,
            "run_status": None,
            "exit_code": None,
            "install_seconds": None,
            "run_seconds": None,
            "run_peak_memory_mib": None,
            "install_peak_memory_mib": None,
        }

    valid = report.get("docker_used") is True and report.get("isolated") is True
    install_status = report.get("dependency_install_status")
    install_success = install_status == "INSTALLED"
    run_success = valid and report.get("exit_code") == 0
    run_peak = (report.get("meta") or {}).get("peak_memory_bytes")
    install_peak = install_meta.get("peak_memory_bytes")
    return {
        "paper_id": paper_id,
        "valid_run": valid,
        "install_success": install_success,
        "run_success": run_success,
        "pilot_success": install_success and run_success,
        "stage_status": (record.get("stage") or {}).get("status", "STAGED"),
        "dependency_install_status": install_status,
        "run_status": report.get("status"),
        "exit_code": report.get("exit_code"),
        "install_seconds": install_meta.get("duration_seconds"),
        "run_seconds": report.get("duration_seconds"),
        "run_peak_memory_mib": round(run_peak / MIB, 1) if isinstance(run_peak, int) else None,
        "install_peak_memory_mib": round(install_peak / MIB, 1) if isinstance(install_peak, int) else None,
    }


def measure(runs_dir: Path = PILOT_RUNS_DIR) -> Dict[str, Any]:
    paper_ids = [e["paper_id"] for e in json.loads(SEED_PAPERS_PATH.read_text(encoding="utf-8"))]
    papers = [paper_measurement(pid, runs_dir) for pid in paper_ids]
    n = len(paper_ids)  # the denominator is always the corpus size (protocol section 5)

    def rate(key: str) -> Dict[str, Any]:
        count = sum(1 for p in papers if p[key])
        return {"count": count, "of": n, "rate": round(count / n, 3) if n else None}

    return {
        "protocol": "docs/PILOT_WEEK2.md",
        "papers": papers,
        "valid_runs": rate("valid_run"),
        "install_success_rate": rate("install_success"),
        "run_success_rate": rate("run_success"),
        "pilot_success_rate": rate("pilot_success"),
    }


def _cell(value: Any) -> str:
    if value is None:
        return "not measured"
    if isinstance(value, bool):
        return "yes" if value else "no"
    return str(value)


def to_markdown(result: Dict[str, Any]) -> str:
    lines: List[str] = [
        "<!-- Generated by scripts/pilot_measurements.py from data/pilot_runs/; do not edit by hand. -->",
        "",
        "| Measure | Count | Rate |",
        "|---|---|---|",
    ]
    for key, label in (("install_success_rate", "Install success"), ("run_success_rate", "Run success"),
                       ("pilot_success_rate", "Pilot success"), ("valid_runs", "Valid runs")):
        r = result[key]
        lines.append(f"| {label} | {r['count']} / {r['of']} | {r['rate']} |")
    lines += [
        "",
        "| Paper | Dependencies | Run status | Exit code | Install (s) | Run (s) | Install peak (MiB) | Run peak (MiB) | Pilot success |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for p in result["papers"]:
        lines.append(
            f"| `{p['paper_id']}` | {_cell(p['dependency_install_status'])} | {_cell(p['run_status'])} | "
            f"{_cell(p['exit_code'])} | {_cell(p['install_seconds'])} | {_cell(p['run_seconds'])} | "
            f"{_cell(p['install_peak_memory_mib'])} | {_cell(p['run_peak_memory_mib'])} | {_cell(p['pilot_success'])} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compute pilot measurements from data/pilot_runs/.")
    parser.add_argument("--runs-dir", default=str(PILOT_RUNS_DIR))
    args = parser.parse_args(argv)
    runs_dir = Path(args.runs_dir)
    result = measure(runs_dir)
    (runs_dir / "measurements.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    markdown = to_markdown(result)
    (runs_dir / "measurements.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
