#!/usr/bin/env python3
"""Put Pilot 1 and Pilot 2 side by side from their stored measurements (docs/PILOT_2.md section 10).

    python scripts/pilot_compare.py

Reads `data/pilot_runs/measurements.json` and `data/pilot2_runs/measurements.json` (written by
scripts/pilot_measurements.py) and `failure_categories.json` of each (scripts/categorize_pilot_failures.py), and
writes `data/pilot2_runs/comparison.json` and `comparison.md`. Pilot 1's numbers are copied unchanged; nothing is typed
by hand. Every number in the Pilot 2 report comes from these files.

With `--pilot3-dir` it puts all three pilots side by side (docs/PILOT_3.md section 9) and writes
`<pilot3-dir>/comparison.json` and `comparison.md`; Pilot 2's comparison files are not touched (#292).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

project_root = Path(__file__).resolve().parent.parent
PILOT1_DIR = project_root / "data" / "pilot_runs"
PILOT2_DIR = project_root / "data" / "pilot2_runs"
PILOT3_DIR = project_root / "data" / "pilot3_runs"
RATES = (("install_success_rate", "Install success"), ("run_success_rate", "Run success"),
         ("pilot_success_rate", "Pilot success"), ("valid_runs", "Valid runs"))


def _load(path: Path) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(f"{path} not found: run scripts/pilot_measurements.py and scripts/categorize_pilot_failures.py first")
    return json.loads(path.read_text(encoding="utf-8"))


def _relative(path: Path) -> str:
    """A repository-relative POSIX path, so the stored file does not depend on the machine that generated it (#246)."""
    try:
        return path.resolve().relative_to(project_root).as_posix()
    except ValueError:
        return path.as_posix()


def compare(pilot1_dir: Path = PILOT1_DIR, pilot2_dir: Path = PILOT2_DIR) -> dict[str, Any]:
    m1, m2 = _load(pilot1_dir / "measurements.json"), _load(pilot2_dir / "measurements.json")
    c1, c2 = _load(pilot1_dir / "failure_categories.json"), _load(pilot2_dir / "failure_categories.json")
    papers = []
    cat1 = {p["paper_id"]: p for p in c1["papers"]}
    cat2 = {p["paper_id"]: p for p in c2["papers"]}
    by1 = {p["paper_id"]: p for p in m1["papers"]}
    by2 = {p["paper_id"]: p for p in m2["papers"]}
    for paper_id in by1:
        papers.append({
            "paper_id": paper_id,
            "pilot1": {"pilot_success": by1[paper_id]["pilot_success"], "category": cat1[paper_id]["category"] or cat1[paper_id]["other_name"],
                       "phase": cat1[paper_id]["phase"]},
            "pilot2": {"pilot_success": by2.get(paper_id, {}).get("pilot_success"), "category": (cat2.get(paper_id) or {}).get("category") or (cat2.get(paper_id) or {}).get("other_name"),
                       "phase": (cat2.get(paper_id) or {}).get("phase")},
        })
    return {
        "sources": {"pilot1": [_relative(pilot1_dir / "measurements.json"), _relative(pilot1_dir / "failure_categories.json")],
                    "pilot2": [_relative(pilot2_dir / "measurements.json"), _relative(pilot2_dir / "failure_categories.json")]},
        "rates": {key: {"pilot1": m1[key], "pilot2": m2[key]} for key, _ in RATES},
        "failure_counts": {"pilot1": c1["counts"], "pilot2": c2["counts"]},
        "papers": papers,
    }


def compare3(pilot1_dir: Path = PILOT1_DIR, pilot2_dir: Path = PILOT2_DIR, pilot3_dir: Path = PILOT3_DIR) -> dict[str, Any]:
    """Pilots 1, 2, and 3 side by side: the two-pilot comparison plus Pilot 3's rates, categories, and per-paper results."""
    result = compare(pilot1_dir, pilot2_dir)
    m3, c3 = _load(pilot3_dir / "measurements.json"), _load(pilot3_dir / "failure_categories.json")
    by3 = {p["paper_id"]: p for p in m3["papers"]}
    cat3 = {p["paper_id"]: p for p in c3["papers"]}
    for p in result["papers"]:
        c = cat3.get(p["paper_id"]) or {}
        p["pilot3"] = {"pilot_success": by3.get(p["paper_id"], {}).get("pilot_success"),
                       "category": c.get("category") or c.get("other_name"), "phase": c.get("phase")}
    result["sources"]["pilot3"] = [_relative(pilot3_dir / "measurements.json"), _relative(pilot3_dir / "failure_categories.json")]
    for key, _ in RATES:
        result["rates"][key]["pilot3"] = m3[key]
    result["failure_counts"]["pilot3"] = c3["counts"]
    return result


def to_markdown3(result: dict[str, Any]) -> str:
    lines = ["<!-- Generated by scripts/pilot_compare.py from the stored measurements; do not edit by hand. -->", "",
             "| Measure | Pilot 1 (`data/pilot_runs/`) | Pilot 2 (`data/pilot2_runs/`) | Pilot 3 (`data/pilot3_runs/`) |",
             "|---|---|---|---|"]
    for key, label in RATES:
        r = result["rates"][key]
        lines.append(f"| {label} | {_fmt(r['pilot1'])} | {_fmt(r['pilot2'])} | {_fmt(r['pilot3'])} |")
    lines += ["", "| Paper | Pilot 1 | Pilot 2 | Pilot 3 |", "|---|---|---|---|"]

    def cell(p: dict[str, Any]) -> str:
        if p["pilot_success"]:
            return "success"
        return f"{p['category'] or 'no failure category'} ({p['phase'] or 'n/a'})"

    for p in result["papers"]:
        lines.append(f"| `{p['paper_id']}` | {cell(p['pilot1'])} | {cell(p['pilot2'])} | {cell(p['pilot3'])} |")
    counts = result["failure_counts"]
    lines += ["", "| Failure category | Pilot 1 | Pilot 2 | Pilot 3 |", "|---|---|---|---|"]
    for category in counts["pilot1"]:
        lines.append(f"| `{category}` | {counts['pilot1'][category]} | {counts['pilot2'].get(category, 0)} | "
                     f"{counts['pilot3'].get(category, 0)} |")
    return "\n".join(lines) + "\n"


def _fmt(rate: dict[str, Any]) -> str:
    return f"{rate['count']} / {rate['of']} ({rate['rate']})"


def to_markdown(result: dict[str, Any]) -> str:
    lines = ["<!-- Generated by scripts/pilot_compare.py from the stored measurements; do not edit by hand. -->", "",
             "| Measure | Pilot 1 (`data/pilot_runs/`) | Pilot 2 (`data/pilot2_runs/`) |", "|---|---|---|"]
    for key, label in RATES:
        lines.append(f"| {label} | {_fmt(result['rates'][key]['pilot1'])} | {_fmt(result['rates'][key]['pilot2'])} |")
    lines += ["", "| Paper | Pilot 1 | Pilot 2 |", "|---|---|---|"]

    def cell(p: dict[str, Any]) -> str:
        if p["pilot_success"]:
            return "success"
        return f"{p['category'] or 'no failure category'} ({p['phase'] or 'n/a'})"

    for p in result["papers"]:
        lines.append(f"| `{p['paper_id']}` | {cell(p['pilot1'])} | {cell(p['pilot2'])} |")
    counts1, counts2 = result["failure_counts"]["pilot1"], result["failure_counts"]["pilot2"]
    lines += ["", "| Failure category | Pilot 1 | Pilot 2 |", "|---|---|---|"]
    for category in counts1:
        lines.append(f"| `{category}` | {counts1[category]} | {counts2.get(category, 0)} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Compare Pilot 1 and Pilot 2 from their stored measurements.")
    parser.add_argument("--pilot1-dir", default=str(PILOT1_DIR))
    parser.add_argument("--pilot2-dir", default=str(PILOT2_DIR))
    parser.add_argument("--pilot3-dir", default="", help="Also compare Pilot 3; writes into this directory only.")
    args = parser.parse_args(argv)
    if args.pilot3_dir:
        result3 = compare3(Path(args.pilot1_dir), Path(args.pilot2_dir), Path(args.pilot3_dir))
        out3 = Path(args.pilot3_dir)
        (out3 / "comparison.json").write_text(json.dumps(result3, indent=2) + "\n", encoding="utf-8")
        markdown3 = to_markdown3(result3)
        (out3 / "comparison.md").write_text(markdown3, encoding="utf-8")
        print(markdown3)
        return 0
    result = compare(Path(args.pilot1_dir), Path(args.pilot2_dir))
    out = Path(args.pilot2_dir)
    (out / "comparison.json").write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
    markdown = to_markdown(result)
    (out / "comparison.md").write_text(markdown, encoding="utf-8")
    print(markdown)
    return 0


if __name__ == "__main__":
    sys.exit(main())
