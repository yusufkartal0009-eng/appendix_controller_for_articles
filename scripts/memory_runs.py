#!/usr/bin/env python3
"""Table of the memory re-runs next to Pilot 3 (#327).

    python scripts/memory_runs.py              # print the table
    python scripts/memory_runs.py --write      # replace the generated block in docs/MEMORY_RUNS.md
    python scripts/memory_runs.py --check      # exit 1 if that block differs from the table

Reads `data/memory_runs/<paper_id>/pilot_record.json` (a run of `scripts/run_pilot.py --pilot3 --memory ... --record-root
data/memory_runs`) and the same paper's record in `data/pilot3_runs/`. Nothing in the table is typed by hand. A memory
re-run is not a protocol run: its memory limit differs from the protocol's.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

project_root = Path(__file__).resolve().parent.parent
DATA = project_root / "data"
DOC_PATH = project_root / "docs" / "MEMORY_RUNS.md"
START, END = "<!-- memory-runs:start -->", "<!-- memory-runs:end -->"
HEADER = "<!-- Generated by scripts/memory_runs.py from data/memory_runs/ and data/pilot3_runs/; do not edit by hand. -->"
GRID_STEP = re.compile(r"grid search:\s+\d+%\|[^|]*\|\s*(\d+)/(\d+)")
GIB = 1024 ** 3
UNITS = {"k": 1024, "m": 1024 ** 2, "g": GIB}


def limit_bytes(text: str) -> int:
    """A Docker memory size such as `6g` or `14265m` in bytes."""
    match = re.fullmatch(r"(\d+)([kmg])", text.strip().lower())
    if not match:
        raise ValueError(f"not a Docker memory size: {text!r}")
    return int(match.group(1)) * UNITS[match.group(2)]


def last_grid_step(stderr_log: Path) -> str:
    """The last grid-search progress counter in a log (`187/540`), or `n/a` when the log has none."""
    if not stderr_log.is_file():
        return "n/a"
    found = GRID_STEP.findall(stderr_log.read_text(encoding="utf-8", errors="replace"))
    return f"{found[-1][0]}/{found[-1][1]}" if found else "n/a"


def summarize(record_dir: Path) -> dict[str, Any]:
    record = json.loads((record_dir / "pilot_record.json").read_text(encoding="utf-8"))
    run = record.get("run") or {}
    limit = record["limits"]["memory_limit"]
    peak = run.get("peak_memory_bytes")
    return {
        "status": run.get("status") or ("STAGING_FAILED" if (record.get("stage") or {}).get("status") == "FAILED" else "n/a"),
        "exit_code": run.get("exit_code"),
        "duration_seconds": run.get("duration_seconds"),
        "peak_memory_bytes": peak,
        "peak_memory_gib": None if peak is None else round(peak / GIB, 2),
        "memory_limit": limit,
        "memory_limit_gib": round(limit_bytes(limit) / GIB, 2),
        "peak_share_of_limit": None if peak is None else round(peak / limit_bytes(limit), 3),
        "last_grid_step": last_grid_step(record_dir / "stderr.log"),
        "memory_override": record.get("memory_override"),
    }


def measure(data: Path = DATA) -> list[dict[str, Any]]:
    rows = []
    for record_dir in sorted((data / "memory_runs").glob("paper_*")):
        if not (record_dir / "pilot_record.json").is_file():
            continue
        pilot3_dir = data / "pilot3_runs" / record_dir.name
        rows.append({"paper_id": record_dir.name, "pilot3": summarize(pilot3_dir), "memory_run": summarize(record_dir)})
    return rows


def _cell(value: Any, unit: str = "") -> str:
    return "n/a" if value is None else f"{value}{unit}"


def to_markdown(rows: list[dict[str, Any]]) -> str:
    columns = "status | duration (s) | peak memory (GiB) | memory limit (GiB) | grid step"
    lines = [HEADER, "", f"| Paper | Pilot 3: {columns} | Memory re-run: {columns} |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for row in rows:
        cells = [f"`{row['paper_id']}`"]
        for key in ("pilot3", "memory_run"):
            r = row[key]
            cells += [f"{r['status']} (exit {_cell(r['exit_code'])})", _cell(r["duration_seconds"]),
                      _cell(r["peak_memory_gib"]), _cell(r["memory_limit_gib"]), r["last_grid_step"]]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def to_sentence(rows: list[dict[str, Any]]) -> str:
    """One sentence per paper for the report: both outcomes and both memory limits."""
    parts = []
    for row in rows:
        a, b = row["pilot3"], row["memory_run"]
        parts.append(f"`{row['paper_id']}`: {a['status']} at {a['memory_limit_gib']} GiB (peak {_cell(a['peak_memory_gib'])} GiB) "
                     f"in Pilot 3, {b['status']} at {b['memory_limit_gib']} GiB (peak {_cell(b['peak_memory_gib'])} GiB) "
                     f"in the memory re-run")
    return "; ".join(parts) + "."


def render_block(data: Path = DATA) -> str:
    return to_markdown(measure(data))


def apply(text: str, data: Path = DATA) -> str:
    if text.count(START) != 1 or text.count(END) != 1:
        raise ValueError("docs/MEMORY_RUNS.md must hold exactly one memory-runs block")
    a, b = text.index(START) + len(START), text.index(END)
    return text[:a] + "\n" + render_block(data) + "\n" + text[b:]


def in_sync(text: str, data: Path = DATA) -> bool:
    return apply(text, data) == text


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Table of the memory re-runs next to Pilot 3.")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--doc", default=str(DOC_PATH))
    args = parser.parse_args(argv)
    if not (args.write or args.check):
        print(render_block())
        return 0
    path = Path(args.doc)
    raw = path.read_bytes().decode("utf-8")
    text = raw.replace("\r\n", "\n")
    if args.check:
        ok = in_sync(text)
        print(json.dumps({"in_sync": ok}))
        return 0 if ok else 1
    new = apply(text)
    path.write_bytes((new.replace("\n", "\r\n") if "\r\n" in raw else new).encode("utf-8"))
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
