#!/usr/bin/env python3
"""Write docs/DIAGNOSIS_EXAMPLES.md: the rule-based diagnosis of every stored run of Pilots 1 to 4, the memory runs, and the CPU runs (#33).

    python scripts/diagnosis_examples.py            # rewrite the document
    python scripts/diagnosis_examples.py --check    # exit 1 if the document differs from what the records give

The text of each report is exactly what `cli.py diagnose <run_dir>` prints; nothing is edited by hand. The first attempts kept
as evidence (`first_attempts/`) are not included.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.diagnosis.report import diagnose_run

DOC_PATH = project_root / "docs" / "DIAGNOSIS_EXAMPLES.md"
GROUPS = (
    ("Pilot 1", "data/pilot_runs", "docs/PILOT_WEEK2.md"),
    ("Pilot 2", "data/pilot2_runs", "docs/PILOT_2.md"),
    ("Pilot 3", "data/pilot3_runs", "docs/PILOT_3.md"),
    ("Pilot 4", "data/pilot4_runs", "docs/PILOT_4.md"),
    ("Memory runs", "data/memory_runs", "docs/MEMORY_RUNS.md"),
    ("CPU runs", "data/cpu_runs", "docs/CPU_RUNS.md"),
)


def run_dirs(base: Path) -> list[Path]:
    return sorted(p for p in base.iterdir() if p.is_dir() and (p / "pilot_record.json").is_file())


def build_document(root: Path = project_root) -> str:
    sections: list[str] = []
    table = ["| Group | Run | Run status | Category |", "|---|---|---|---|"]
    for title, rel, protocol in GROUPS:
        base = root / rel
        sections.append(f"## {title}\n\nRecords: `{rel}/` ({protocol}).\n")
        for folder in run_dirs(base):
            report = diagnose_run(folder)
            shown = folder.relative_to(root).as_posix()
            report.run_dir = shown
            status = next((s.text for s in report.statements if s.text.startswith("The run phase ended with status")), "")
            status = status.removeprefix("The run phase ended with status ").split(" ")[0] if status else "unknown"
            table.append(f"| {title} | `{shown}` | {status} | {report.category_label or '-'} |")
            body = report.to_markdown().replace("# Diagnosis of", "### Diagnosis of", 1).replace("\n## ", "\n#### ")
            sections.append(body)
    head = ("# Examples of the rule-based diagnosis\n\n"
            "<!-- Generated by scripts/diagnosis_examples.py from the stored runs; do not edit by hand. -->\n\n"
            "Each report below is the output of `python cli.py diagnose <run dir>` (docs/DIAGNOSIS.md) for one stored run. "
            "The claims in the reports are the `expected_claims` of `data/seed_papers.json` for the seed papers; the runs of "
            "the corpus expansion (Pilot 4) have none. The reports state what the files say; they are not scores.\n\n")
    return head + "\n".join(table) + "\n\n" + "\n".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build_document()
    if args.check:
        current = DOC_PATH.read_text(encoding="utf-8").replace("\r\n", "\n") if DOC_PATH.is_file() else ""
        if current != text:
            print(f"{DOC_PATH.name} differs from the records; run scripts/diagnosis_examples.py", file=sys.stderr)
            return 1
        return 0
    DOC_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC_PATH} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
