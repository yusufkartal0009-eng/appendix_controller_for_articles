#!/usr/bin/env python3
"""Write docs/DIAGNOSIS_COMPARISONS.md: rule-based comparisons of stored runs of the same paper (#35).

    python scripts/diagnosis_comparisons.py            # rewrite the document
    python scripts/diagnosis_comparisons.py --check    # exit 1 if the document differs from what the records give

Pairs: the Pilot 3 run of `paper_003` and `paper_006` against their other stored runs (Pilot 2, memory runs, CPU runs), the
seed runs of `data/multi_seed_runs/` when they exist, and the synthetic seed runs of `data/synthetic_seeds/`. Run A is the
reference of each pair. Nothing is edited by hand.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

project_root = Path(__file__).resolve().parent.parent
if str(project_root) not in sys.path:
    sys.path.insert(0, str(project_root))

from src.diagnosis.compare import compare_runs

DOC_PATH = project_root / "docs" / "DIAGNOSIS_COMPARISONS.md"
FIXED_PAIRS = (
    ("data/pilot3_runs/paper_003", "data/pilot2_runs/paper_003"),
    ("data/pilot3_runs/paper_003", "data/memory_runs/paper_003"),
    ("data/pilot3_runs/paper_003", "data/memory_runs/paper_003_run2"),
    ("data/pilot3_runs/paper_003", "data/cpu_runs/paper_003"),
    ("data/pilot3_runs/paper_006", "data/pilot2_runs/paper_006"),
    ("data/pilot3_runs/paper_006", "data/memory_runs/paper_006_run2"),
    ("data/pilot3_runs/paper_006", "data/cpu_runs/paper_006"),
    ("data/synthetic_seeds/synthetic_seed_free/seed_1", "data/synthetic_seeds/synthetic_seed_free/seed_2"),
    ("data/synthetic_seeds/synthetic_seeded/seed_1", "data/synthetic_seeds/synthetic_seeded/seed_2"),
)


def seed_pairs(root: Path) -> list[tuple[str, str]]:
    """Every seed run of data/multi_seed_runs/<paper> against the first one (by folder name)."""
    pairs: list[tuple[str, str]] = []
    base = root / "data" / "multi_seed_runs"
    if not base.is_dir():
        return pairs
    for paper in sorted(p for p in base.iterdir() if p.is_dir()):
        seeds = sorted((p for p in paper.glob("seed_*") if (p / "pilot_record.json").is_file()),
                       key=lambda p: int(p.name.split("_")[1]))
        pairs += [(seeds[0].relative_to(root).as_posix(), other.relative_to(root).as_posix()) for other in seeds[1:]]
    return pairs


def build_document(root: Path = project_root) -> str:
    pairs = [(a, b) for a, b in [*FIXED_PAIRS, *seed_pairs(root)] if (root / a).is_dir() and (root / b).is_dir()]
    table = ["| A (reference) | B | Metrics | Recorded differences | Review suggested |", "|---|---|---|---|---|"]
    bodies = []
    for a, b in pairs:
        report = compare_runs(root / a, root / b, a, b)
        table.append(f"| `{a}` | `{b}` | {report.metric_outcome} | {', '.join(report.differing_factors) or 'none'} | "
                     f"{'yes' if report.review_suggested else 'no'} |")
        bodies.append(report.to_markdown().replace("# Comparison", "### Comparison", 1).replace("\n## ", "\n#### "))
    head = ("# Comparisons of stored runs\n\n"
            "<!-- Generated by scripts/diagnosis_comparisons.py from the stored runs; do not edit by hand. -->\n\n"
            "Rule-based comparisons (docs/DIAGNOSIS.md section 8) of stored runs of the same paper. The first column is the "
            "reference run of each pair. The reports list recorded differences; they do not name a cause.\n\n")
    return head + "\n".join(table) + "\n\n" + "\n".join(bodies)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = build_document()
    if args.check:
        current = DOC_PATH.read_text(encoding="utf-8").replace("\r\n", "\n") if DOC_PATH.is_file() else ""
        if current != text:
            print(f"{DOC_PATH.name} differs from the records; run scripts/diagnosis_comparisons.py", file=sys.stderr)
            return 1
        return 0
    DOC_PATH.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {DOC_PATH} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
