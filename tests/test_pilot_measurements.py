"""Pilot measurements apply the definitions frozen in docs/PILOT_WEEK2.md section 5 (P3, #124).

The data here is synthetic and only exercises the rules; real results live in data/pilot_runs/.
"""

import json

import pytest

import scripts.pilot_measurements as pm

PAPERS = [{"paper_id": f"paper_{i:03d}"} for i in (1, 2, 3, 4, 5, 6)]


@pytest.fixture
def runs_dir(tmp_path, monkeypatch):
    seed = tmp_path / "seed.json"
    seed.write_text(json.dumps(PAPERS))
    monkeypatch.setattr(pm, "SEED_PAPERS_PATH", seed)
    return tmp_path / "runs"


def _write(runs_dir, paper_id, report=None, install_meta=None, record=None):
    d = runs_dir / paper_id
    d.mkdir(parents=True)
    if report is not None:
        (d / "run_report.json").write_text(json.dumps(report))
    if install_meta is not None:
        (d / "install_meta.json").write_text(json.dumps(install_meta))
    (d / "pilot_record.json").write_text(json.dumps(record or {"stage": {"status": "STAGED"}}))


def _report(**overrides):
    report = {"docker_used": True, "isolated": True, "dependency_install_status": "INSTALLED", "status": "COMPLETED",
              "exit_code": 0, "duration_seconds": 12.5, "meta": {"peak_memory_bytes": 300 * 1024 * 1024}}
    report.update(overrides)
    return report


def test_definitions_and_fixed_denominator(runs_dir):
    _write(runs_dir, "paper_001", _report(), {"duration_seconds": 4.0, "peak_memory_bytes": 50 * 1024 * 1024})
    _write(runs_dir, "paper_002", _report(dependency_install_status="SKIPPED"))  # ran, nothing installed
    _write(runs_dir, "paper_003", _report(status="TIMEOUT", exit_code=137))
    _write(runs_dir, "paper_004", _report(dependency_install_status="FAILED", status="FAILED", exit_code=1))
    _write(runs_dir, "paper_005", _report(docker_used=False, isolated=False))  # not a valid run
    _write(runs_dir, "paper_006", record={"stage": {"status": "FAILED"}})  # staging failed, no report

    result = pm.measure(runs_dir)
    by_id = {p["paper_id"]: p for p in result["papers"]}

    assert result["install_success_rate"] == {"count": 3, "of": 6, "rate": 0.5}  # 001, 003, 005
    assert result["run_success_rate"] == {"count": 2, "of": 6, "rate": 0.333}  # 001, 002 (005 is not valid)
    assert result["pilot_success_rate"] == {"count": 1, "of": 6, "rate": 0.167}  # 001 only
    assert result["valid_runs"]["count"] == 4

    assert by_id["paper_002"]["run_success"] and not by_id["paper_002"]["pilot_success"]
    assert not by_id["paper_005"]["run_success"]
    assert by_id["paper_006"]["stage_status"] == "FAILED" and not by_id["paper_006"]["pilot_success"]
    assert by_id["paper_001"]["run_peak_memory_mib"] == 300.0
    assert by_id["paper_001"]["install_seconds"] == 4.0


def test_missing_measurements_are_reported_as_not_measured(runs_dir):
    _write(runs_dir, "paper_001", _report(meta={"peak_memory_bytes": None}))
    result = pm.measure(runs_dir)
    row = next(line for line in pm.to_markdown(result).splitlines() if "`paper_001`" in line)
    assert row.count("not measured") == 3  # install seconds, install peak, run peak


def test_main_writes_json_and_markdown(runs_dir):
    _write(runs_dir, "paper_001", _report())
    assert pm.main(["--runs-dir", str(runs_dir)]) == 0
    assert json.loads((runs_dir / "measurements.json").read_text())["pilot_success_rate"]["of"] == 6
    assert (runs_dir / "measurements.md").read_text().startswith("<!-- Generated by scripts/pilot_measurements.py")


def test_committed_measurements_match_the_stored_runs():
    """measurements.json/.md must be regenerated whenever data/pilot_runs/ changes."""
    stored = pm.PILOT_RUNS_DIR / "measurements.json"
    if not stored.exists():
        pytest.skip("no pilot results stored yet")
    result = pm.measure()
    assert json.loads(stored.read_text(encoding="utf-8")) == result
    assert (pm.PILOT_RUNS_DIR / "measurements.md").read_text(encoding="utf-8") == pm.to_markdown(result)
